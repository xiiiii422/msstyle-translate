/* ==========================================================================
 * config.js —— 可选的外部配置（部署者用）
 *
 * 这个文件是【可选】的。不创建它，页面也能正常工作：
 * 访客可以在页面右上角「设置」里自己填 API Key。
 *
 * ─────────────────────────────────────────────────────────────
 *  【商用推荐】用代理模式：API Key 放服务端，前端完全不接触
 * ─────────────────────────────────────────────────────────────
 *
 *   window.__MSSTYLE_CONFIG__ = {
 *     proxyUrl: "/api"        // 同源反代（推荐）
 *     // 或 "https://xxx.workers.dev"（Cloudflare Worker）
 *   };
 *
 *  然后部署 proxy/ 下的代理服务，把 Key 放进服务端环境变量。
 *  详见 README 第 5 节「商用部署」。代理就绪后，设置面板里的
 *  API Key / 模型选项会自动隐藏，访客打开即用。
 *
 * ─────────────────────────────────────────────────────────────
 *  【个人娱乐】纯静态直连：Key 会在前端暴露
 * ─────────────────────────────────────────────────────────────
 *
 *   window.__MSSTYLE_CONFIG__ = {
 *     apiKey: "你的智谱 API Key",     // ⚠️ 所有访客都能看到
 *     model: "glm-4-flash-250414",
 *     fallbackModels: ["glm-4-flash"],
 *     apiUrl: "https://open.bigmodel.cn/api/paas/v4/chat/completions"
 *   };
 *
 * 优先级：访客自己填的 Key  >  config.js 里的  >  script.js 里的常量
 *
 * 安全建议：把 config.js 加进 .gitignore，用 CI/部署平台的环境变量生成它，
 * 这样 Key 就不会进代码仓库。
 * ========================================================================== */

